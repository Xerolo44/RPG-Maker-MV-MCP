import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { parsePluginsJs, readEnabledPlugins, readPluginList } from "../dist/tools/pluginTools.js";
import { buildProjectIndex } from "../dist/eventIndex.js";
import { analyzeProgression } from "../dist/progression.js";
import { createFixtureProject } from "./helpers/fixtureProject.mjs";

const entries = [
  { name: "Community_Basic", status: true, description: "Basic", parameters: { cacheLimit: "20" } },
  { name: "YEP_Core", status: true, description: "", parameters: {} },
  { name: "Off", status: false, description: "", parameters: {} },
];
const body = (list) => `[\n${list.map((e) => JSON.stringify(e)).join(",\n")}\n]`;

test("parsePluginsJs: the RPG Maker layout (comments, var, newline before the array, semicolon)", () => {
  const text = `// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n${body(entries)};\n`;
  assert.deepEqual(parsePluginsJs(text), entries);
});

test("parsePluginsJs: tolerates var/let/const, whitespace, BOM, CRLF and a missing semicolon", () => {
  for (const decl of ["var", "let", "const"]) {
    assert.deepEqual(parsePluginsJs(`${decl}   $plugins\t=\t${body(entries)}`), entries, decl);
  }
  assert.deepEqual(parsePluginsJs(`﻿// Generated\r\nvar $plugins =\r\n${body(entries).replace(/\n/g, "\r\n")};\r\n`), entries);
  assert.deepEqual(parsePluginsJs(`$plugins=${body(entries)}`), entries);
});

test("parsePluginsJs: header comments that contain brackets do not confuse it", () => {
  const text =
    "// Generated by RPG Maker [do not edit]\n" +
    "/* old list: [ {\"name\": \"Gone\", \"status\": true} ]\n   ] [ */\n" +
    "// $plugins = [ \"decoy\" ]\n" +
    `var $plugins = /* the real one [ ] */\n${body(entries)};\n// trailing [comment]\n`;
  assert.deepEqual(parsePluginsJs(text), entries);
});

test("parsePluginsJs: brackets and comment markers inside strings are data", () => {
  const tricky = [{ name: "A", status: true, description: "x ] // [ /* y", parameters: { p: "[1,2]" } }];
  assert.deepEqual(parsePluginsJs(`var $plugins =\n${body(tricky)};\n`), tricky);
});

test("parsePluginsJs: a trailing comma before ] (and before }) is tolerated", () => {
  assert.deepEqual(parsePluginsJs(`var $plugins = [\n${JSON.stringify(entries[1])},\n];`), [entries[1]]);
  assert.deepEqual(parsePluginsJs(`var $plugins = [\n{"name":"A","status":true,"parameters":{"k":"v",},},\n];`), [
    { name: "A", status: true, parameters: { k: "v" } },
  ]);
  // a comma inside a string that looks like a trailing comma is left alone
  assert.deepEqual(parsePluginsJs(`var $plugins = [{"name":"a,]","status":true}];`), [{ name: "a,]", status: true }]);
  assert.deepEqual(parsePluginsJs("var $plugins = [];"), []);
});

test("parsePluginsJs: text after the array is ignored", () => {
  assert.deepEqual(parsePluginsJs(`var $plugins = ${body(entries)};\nvar other = [1, 2];\n`), entries);
});

test("parsePluginsJs: throws on garbage, a missing array, an unterminated array and bad JSON", () => {
  for (const text of ["garbage", "var $plugins = ;", "var $plugins = [ {\"name\": 1 ", "var $plugins = [ {not json ];", "// only a [comment]", "var $plugins = {};"]) {
    assert.throws(() => parsePluginsJs(text), /plugin/i, text);
  }
});

test("parsePluginsJs: a 10 MB file finishes quickly", () => {
  const many = Array.from({ length: 60_000 }, (_, i) => ({ name: `Plugin${i}`, status: i % 2 === 0, description: "d".repeat(120), parameters: { k: "[v]" } }));
  const text = `// header [x]\nvar $plugins =\n${body(many)};\n`;
  assert.ok(text.length > 10_000_000, `size ${text.length}`);
  const t0 = performance.now();
  const parsed = parsePluginsJs(text);
  const ms = performance.now() - t0;
  assert.equal(parsed.length, 60_000);
  assert.ok(ms < 3000, `took ${ms.toFixed(0)} ms`);
});

test("parsePluginsJs: a 10 MB comment before the array and a 10 MB junk file do not hang", () => {
  const t0 = performance.now();
  const comment = `/*${"[ ".repeat(5_000_000)}*/\nvar $plugins = [];`;
  assert.deepEqual(parsePluginsJs(comment), []);
  assert.throws(() => parsePluginsJs("[".repeat(10_000_000)), /plugin/i);
  assert.ok(performance.now() - t0 < 5000);
});

async function withPluginsJs(text, fn) {
  const fx = await createFixtureProject({});
  try {
    if (text !== undefined) {
      await fs.mkdir(path.join(fx.root, "js"), { recursive: true });
      await fs.writeFile(path.join(fx.root, "js", "plugins.js"), text, "utf8");
    }
    return await fn(fx);
  } finally {
    await fx.cleanup();
  }
}

test("readPluginList keeps working on a normal file and now on a header comment with brackets", async () => {
  await withPluginsJs(`// Generated [by] RPG Maker.\nvar $plugins =\n${body(entries)};\n`, async ({ project }) => {
    assert.deepEqual(await readPluginList(project), entries);
  });
  await withPluginsJs(undefined, async ({ project }) => assert.deepEqual(await readPluginList(project), []));
  await withPluginsJs("garbage", async ({ project }) => {
    await assert.rejects(readPluginList(project), /plugin array/);
  });
  await withPluginsJs("var $plugins = [ {not json ];", async ({ project }) => {
    await assert.rejects(readPluginList(project), /Could not parse plugin list/);
  });
});

test("readEnabledPlugins: names, unreadable flag", async () => {
  const ok = `// [c]\nvar $plugins =\n${body(entries)};\n`;
  await withPluginsJs(ok, async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: ["Community_Basic", "YEP_Core"], unreadable: false }));
  await withPluginsJs(undefined, async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: [], unreadable: false }));
  await withPluginsJs("", async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: [], unreadable: false }));
  await withPluginsJs("  \r\n﻿ ", async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: [], unreadable: false }));
  await withPluginsJs("var $plugins = [];", async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: [], unreadable: false }));
  for (const bad of ["garbage", "var $plugins = [ {not json ];", "var $plugins = ['single'];"]) {
    await withPluginsJs(bad, async ({ project }) => assert.deepEqual(await readEnabledPlugins(project), { names: [], unreadable: true }, bad));
  }
});

test("the index records pluginsUnreadable and the analysis lowers its confidence with a note", async () => {
  await withPluginsJs("var $plugins = [ {not json ];", async ({ project }) => {
    const index = await buildProjectIndex(project);
    assert.equal(index.hidden.pluginsUnreadable, true);
    assert.equal(index.hidden.enabledPlugins, 0);
    const report = analyzeProgression(index, { limit: 10 });
    assert.equal(report.uncertainty.confidence, "low");
    assert.ok(report.notes.includes("js/plugins.js could not be read, so enabled plugins are unknown"), report.notes.join("\n"));
  });
  await withPluginsJs(`// [ok]\nvar $plugins =\n${body([entries[0], entries[2]])};\n`, async ({ project }) => {
    const index = await buildProjectIndex(project);
    assert.equal(index.hidden.pluginsUnreadable, false);
    assert.equal(analyzeProgression(index, { limit: 10 }).uncertainty.confidence, "high");
  });
  await withPluginsJs(undefined, async ({ project }) => {
    assert.equal((await buildProjectIndex(project)).hidden.pluginsUnreadable, false);
  });
});

test("a comment with a bracket before the array no longer hides the enabled plugins from the index", async () => {
  await withPluginsJs(`// Generated [by RPG Maker]\nvar $plugins =\n${body(entries)};\n`, async ({ project }) => {
    const { hidden } = await buildProjectIndex(project);
    assert.equal(hidden.enabledPlugins, 1);
    assert.deepEqual(hidden.enabledPluginNames, ["YEP_Core"]);
    assert.equal(hidden.pluginsUnreadable, false);
  });
});
